# loop should start sequentially through the urls and download them one by one, if it fails to download a url, it should retry up to 3 times before moving on to the next url.
for url in AwillEternalurls:
    for attempt in range(maxRetries):
        try:
            print(f"Attempting to download: {url} (Attempt {attempt + 1}/{maxRetries})")
            ydl_opts = {
                'outtmpl': f'{AwillEternalSaveLocation}/%(title)s.%(ext)s',
                # specify 720px format for video and best audio format
                'format': 'bestvideo[height=720]+bestaudio/best',
                'noplaylist': True,
                'writesubtitles': True,
                'writeautomaticsub': True,
                'subtitleslangs': ['en'],
                # 'cookiesfrombrowser': ('brave',)
            }
            with yt_dlp.YoutubeDL(ydl_opts) as ydl:
                ydl.download([url])
            print(f"Successfully downloaded: {url}")
            break  # Exit the retry loop if download is successful
        except Exception as e:
            print(f"Attempt {attempt + 1} failed for {url}: {e}")

            if attempt == maxRetries - 1:
                print(f"Failed to download {url} after {maxRetries} attempts. proceeding to the next URL.")
                continue  # Move on to the next URL after max retries
